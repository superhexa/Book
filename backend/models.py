# ---------------------------------------------------------------------------
# Helper for schema docs
# ---------------------------------------------------------------------------


def _shape(description, required, fields):
    """Build a documented schema dict (documentation/validation reference)."""
    return {
        "description": description,
        "required": list(required),
        "fields": dict(fields),
    }

