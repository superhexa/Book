"""Phase 2 data layer — Jordanian football platform collections.

This module documents the shape of every MongoDB collection used by the
Jordanian football platform (Phase 2) and by the pre-existing TurfBook
booking stack (Phase 1). MongoDB has no server-side schema here, so the
document shapes below are the contract: route handlers and services MUST
validate against these shapes (see ``*_SCHEMA`` dicts) and indexes are
enforced by :func:`migrations.ensure_indexes`.

Conventions (shared with Phase 1):
- ``_id`` is ALWAYS a string uuid-hex generated by ``db.new_id()``
  (never an ObjectId).
- Timestamps are tz-aware UTC datetimes via ``db.now()``; use ``db.ser()``
  / ``db.ser_many()`` to serialize documents for JSON responses.
- Soft delete: entity collections carry ``deleted_at`` (None = alive).
  Reference/geography collections are hard-kept and deactivated with
  ``is_active`` instead.
- ``*_SCHEMA`` dicts describe ``required`` fields, ``fields`` (type /
  enum / foreign-key notes). They are documentation + a validation
  reference for services; they are NOT enforced by Mongo itself.

CROSS-COLLECTION INTEGRITY RULES (enforced in service code, not in Mongo):
1. ``standings`` / ``player_statistics`` / ``team_statistics`` are DERIVED
   aggregates. They may only be (re)calculated from ``matches`` with
   status FINISHED (or UNDER_REVIEW-resolved) via the recalc service.
   Never write them by hand from user input.
2. ``match_events`` are IMMUTABLE once the parent match reaches FINISHED.
   Corrections after FINISHED require the ``matches.result`` permission
   and must be written through the result-amendment flow (which re-runs
   the stats recalc and writes an ``audit_logs`` entry).
3. A ``match`` belongs to exactly one competition context: either
   (league_id + season_id [+ division_id]) or (tournament_id). Never both.
4. ``fixtures`` are schedule slots created by the fixture generator.
   A ``match`` created from a fixture MUST set ``match.fixture_id``;
   deleting/replacing a fixture must not orphan its match.
5. ``league_teams`` is the single source of truth for "team X plays in
   league Y season Z". ``standings`` rows are only created for teams
   present in ``league_teams`` with status APPROVED.
6. ``team_members`` (team_id, user_id) unique: a user has exactly one
   membership row per team; role changes update the row, they never add
   a second one. Deleting a team cascades (soft-deletes) its members,
   invitations and entries.
7. ``player_profiles.user_id`` is 1:1 with ``users._id``. A player row in
   a match lineup or event references the *user* id; display data comes
   from ``player_profiles``.
8. ``referee_assignments`` reference ``matches`` + ``referees``. A referee
   cannot be assigned twice to the same match in the same role
   (unique index), and assignments for a FINISHED match are frozen.
9. ``disputes`` targeting a match may only be OPENed while the match is
   not FINISHED, or within the protest window after FINISHED
   (``settings`` key ``match_protest_window_hours``).
10. ``push_subscriptions`` (user_id, endpoint) unique: re-subscribing the
    same browser endpoint updates the row, never duplicates it.
11. ``settings._id`` IS the setting key (e.g. ``"site_name"``) — upsert by
    key only.
12. Geography hierarchy: governorates -> cities -> areas. Teams, leagues,
    referees and facilities reference geography by *key* (stable slugs),
    never by denormalized names, so renames don't break references.
"""

